// Builds the playlist from the mp3/ogg/m4a files in www/music (or ./music if www/music is missing).
// Writes www/music/playlist.json (read by the game at runtime, no rebuild needed) and www/js/playlist.js (fallback).
// Titles come from the files' ID3 tags (artist + title) when present, otherwise from the file name.
// Run after adding or removing songs:  node tools/make-playlist.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = [path.join(root, 'www', 'music'), path.join(root, 'music')].find((d) => fs.existsSync(d));
if (!dir) { console.log('No music folder found (expected www/music).'); process.exit(1); }
const files = fs.readdirSync(dir).filter((f) => /\.(mp3|ogg|m4a|wav|flac)$/i.test(f)).sort();

function text(buf) {
  if (!buf.length) return '';
  const enc = buf[0], b = buf.subarray(1);
  let s;
  if (enc === 1 || enc === 2) {
    let le = enc === 1 ? !(b[0] === 0xfe && b[1] === 0xff) : false;
    let body = b; if (enc === 1 && ((b[0] === 0xff && b[1] === 0xfe) || (b[0] === 0xfe && b[1] === 0xff))) body = b.subarray(2);
    s = Buffer.from(body); if (!le) s.swap16(); s = s.toString('utf16le');
  } else s = b.toString(enc === 3 ? 'utf8' : 'latin1');
  return s.replace(/\0+$/g, '').split('\0')[0].trim();
}
function id3(file) {
  try {
    const fd = fs.openSync(file, 'r'); const head = Buffer.alloc(10); fs.readSync(fd, head, 0, 10, 0);
    if (head.toString('latin1', 0, 3) !== 'ID3') { fs.closeSync(fd); return {}; }
    const ver = head[3], size = ((head[6] & 127) << 21) | ((head[7] & 127) << 14) | ((head[8] & 127) << 7) | (head[9] & 127);
    const buf = Buffer.alloc(Math.min(size, 1 << 20)); fs.readSync(fd, buf, 0, buf.length, 10); fs.closeSync(fd);
    const out = {}; let i = 0;
    while (i + 10 <= buf.length) {
      let id, len, hdr;
      if (ver === 2) { id = buf.toString('latin1', i, i + 3); len = (buf[i + 3] << 16) | (buf[i + 4] << 8) | buf[i + 5]; hdr = 6; }
      else { id = buf.toString('latin1', i, i + 4); len = ver === 4 ? ((buf[i + 4] & 127) << 21) | ((buf[i + 5] & 127) << 14) | ((buf[i + 6] & 127) << 7) | (buf[i + 7] & 127) : buf.readUInt32BE(i + 4); hdr = 10; }
      if (!/^[A-Z0-9]{3,4}$/.test(id) || len <= 0 || i + hdr + len > buf.length) break;
      const body = buf.subarray(i + hdr, i + hdr + len);
      if (id === 'TIT2' || id === 'TT2') out.title = text(body);
      if (id === 'TPE1' || id === 'TP1') out.artist = text(body);
      i += hdr + len;
    }
    return out;
  } catch { return {}; }
}
const nice = (f) => { const b = f.replace(/\.[^.]+$/, ''); const m = b.match(/^(.*?) - .*? - \d+ (.*)$/); return m ? `${m[1]} \u2014 ${m[2]}` : b; };
const list = files.map((f) => {
  const t = id3(path.join(dir, f));
  return { file: 'music/' + f, title: t.title ? (t.artist ? `${t.artist} \u2014 ${t.title}` : t.title) : nice(f) };
});
fs.writeFileSync(path.join(dir, 'playlist.json'), JSON.stringify(list, null, 2) + '\n');
fs.writeFileSync(path.join(root, 'www', 'js', 'playlist.js'), '// generated by tools/make-playlist.mjs\nexport const PLAYLIST = ' + JSON.stringify(list, null, 2) + ';\n');
console.log(`${list.length} track(s) written to ${path.relative(root, path.join(dir, 'playlist.json'))} and www/js/playlist.js`);
for (const t of list) console.log('  ' + t.title);
