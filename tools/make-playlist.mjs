// Builds www/js/playlist.js from the mp3/ogg/m4a files in www/music (or ./music if www/music is missing).
// Run after adding or removing songs:  node tools/make-playlist.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = [path.join(root, 'www', 'music'), path.join(root, 'music')].find((d) => fs.existsSync(d));
if (!dir) { console.log('No music folder found (expected www/music).'); process.exit(1); }
const files = fs.readdirSync(dir).filter((f) => /\.(mp3|ogg|m4a|wav|flac)$/i.test(f)).sort();
const nice = (f) => { const b = f.replace(/\.[^.]+$/, ''); const m = b.match(/^(.*?) - .*? - \d+ (.*)$/); return m ? `${m[1]} \u2014 ${m[2]}` : b; };
const list = files.map((f) => ({ file: 'music/' + f, title: nice(f) }));
fs.writeFileSync(path.join(root, 'www', 'js', 'playlist.js'), '// generated by tools/make-playlist.mjs\nexport const PLAYLIST = ' + JSON.stringify(list, null, 2) + ';\n');
console.log(`${list.length} track(s) written to www/js/playlist.js`);
