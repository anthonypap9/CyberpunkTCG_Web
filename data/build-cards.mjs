// Generates www/js/carddata.js from data/raw.txt (official card pages, Oct 2026). Run: node data/build-cards.mjs
import fs from 'node:fs';
const rows = fs.readFileSync(new URL('./raw.txt', import.meta.url), 'utf8').trim().split('\n').map((l) => l.split(' | '));
const out = [];
for (const r of rows) {
  if (r.length < 12) { console.error('bad row', r[0], r.length); continue; }
  const [id, name, sub, type, color, cost, power, ram, tags, kws, rarity, ...rest] = r;
  const text = rest.join(' | ').replace(/ \/\/ /g, '\n').replace(/\{([^}]+)\}/g, (_, k) => k.toUpperCase()).replace(/^-$/, '');
  const num = (x) => (x === '-' ? null : Number(x));
  const kwl = kws.toLowerCase();
  const kw = {};
  if (/blocker/.test(kwl)) kw.blocker = true;
  if (/go solo/.test(kwl)) kw.goSolo = true;
  if (/quick/.test(kwl)) kw.quick = true;
  if (/adrenaline/.test(kwl)) kw.adrenaline = true;
  const t = type.toLowerCase();
  const o = { id, name, ...(sub !== '-' ? { sub } : {}), type: t, color: color.toLowerCase(), cost: num(cost), power: t === 'program' ? undefined : num(power), ram: num(ram) ?? 0,
    tags: tags === '-' ? [] : tags.split(',').map((x) => x.trim().toUpperCase()).filter(Boolean), kw, rarity, text };
  if (t === 'gear' || t === 'program') o.sell = true; // assumption: the sell tag is printed only on the card face (see README)
  out.push(o);
}
fs.writeFileSync(new URL('../www/js/carddata.js', import.meta.url), '// AUTO-GENERATED by data/build-cards.mjs from official card pages. Do not edit by hand.\nexport const RAW_CARDS = ' + JSON.stringify(out, null, 0).replace(/\},\{/g, '},\n{') + ';\n');
console.log(out.length, 'cards');
